/** Refresh only upgrade-owned inventories, without changing the Pokeweb checkout. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { analyzeMoveAnimationScript } from "@pokeweb/pokeweb/moveAnimationDiagnostics";
import { decompileMoveAnimationBytes } from "@pokeweb/pokeweb/moveAnimationModel";
import { parseSpaArchive } from "@pokeweb/pokeweb/nitroSpa";

const root = fileURLToPath(new URL("../../../data/graphics/", import.meta.url));
const moveReadme = `${root}move_animations/README.md`;
const spaReadme = `${root}move_spas/README.md`;
const previous = readFileSync(moveReadme, "utf8");
// Keep the reviewed names already owned by this checkout, not another branch's IDs.
const names = new Map([...previous.matchAll(/^\| (\d+) \| ([^|]+) \|/gm)]
  .map(m => [Number(m[1]), m[2].trim()]));
const hash = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const loaded = new Map<number, number[]>();
const moves: string[] = [];
for (const file of readdirSync(`${root}move_animations`).filter(f => /^5_\d+\.bin$/.test(f)).sort()) {
  const id = Number(file.slice(2, -4));
  const bytes = readFileSync(`${root}move_animations/${file}`);
  const analysis = analyzeMoveAnimationScript(decompileMoveAnimationBytes(bytes));
  loaded.set(id, analysis.loadedSpaIds);
  const backgrounds = [...new Set(analysis.backgrounds.filter(e => e.command === "LoadBackground")
    .map(e => e.backgroundId).filter((id): id is number => id !== undefined))].sort((a,b) => a-b);
  const calls = [...new Set(analysis.events.filter(e => e.command === "CallMoveAnimation")
    .map(e => e.params[0]).filter(id => id >= 0))].sort((a,b) => a-b);
  moves.push(`| ${id} | ${names.get(id) ?? `Move ${id}`} | ${analysis.loadedSpaIds.join(", ") || "none"} | ${backgrounds.join(", ") || "none"} | ${calls.join(", ") || "none"} | ${bytes.length} | \`${hash(bytes)}\` |`);
}
const spas: string[] = [];
for (const file of readdirSync(`${root}move_spas`).filter(f => /^6_\d+\.bin$/.test(f)).sort()) {
  const id = Number(file.slice(2, -4));
  const bytes = readFileSync(`${root}move_spas/${file}`);
  const spa = parseSpaArchive(bytes);
  const users = [...loaded].filter(([,ids]) => ids.includes(id)).map(([move]) => move);
  spas.push(`| ${id} | ${spa.resourceCount} | ${spa.textureCount} | ${users.join(", ") || "none"} | ${bytes.length} | \`${hash(bytes)}\` |`);
}
for (const [path, rows] of [[moveReadme, moves], [spaReadme, spas]] as const) {
  const text = readFileSync(path, "utf8");
  const firstRow = /^\| \d+ \|/m.exec(text)?.index;
  if (firstRow === undefined) throw new Error(`Missing ownership rows in ${path}`);
  const prefix = text.slice(0, firstRow)
    .replace(/^<!-- Generated.*?-->/, "<!-- Generated by refresh-animation-ownership.ts or npm run moveanim:docs. Do not hand-edit. -->");
  if (!prefix.includes("|---")) throw new Error(`Missing ownership table in ${path}`);
  writeFileSync(path, `${prefix}${rows.join("\n")}\n`);
}
console.log(`Refreshed ${moves.length} animation and ${spas.length} SPA inventory rows.`);
